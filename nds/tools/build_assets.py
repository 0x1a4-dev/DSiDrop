"""Import the supplied DSiDrop pictogram into the DS 32px/16-color format.

brand-source.png is the unmodified user-supplied wordmark. Only the pictogram
on its left is imported; the lettering never enters the native icon. The GUI
keeps its own palette, so banner colors cannot change unrelated text or keys.
"""
from pathlib import Path
import struct

from PIL import Image

root = Path(__file__).resolve().parents[1]
assets = root / "assets"
source_image = Image.open(assets / "brand-source.png").convert("RGBA")


pictogram = source_image.crop((0, 0, 440, source_image.height))
bounds = pictogram.getchannel("A").point(lambda alpha: 255 if alpha >= 128 else 0).getbbox()
assert bounds is not None, "The source logo has no opaque pictogram"
pictogram = pictogram.crop(bounds)
pictogram.thumbnail((30, 30), Image.Resampling.LANCZOS)
native = Image.new("RGBA", (32, 32))
native.alpha_composite(pictogram, ((32 - pictogram.width) // 2, (32 - pictogram.height) // 2))
quantized = native.convert("RGB").quantize(colors=15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
colors = quantized.getpalette()[:45]
icon_palette = [(0, 0, 0)] + [tuple(colors[i:i + 3]) for i in range(0, 45, 3)]
indices = list(quantized.get_flattened_data())
pixels = [indices[y * 32 + x] + 1 if native.getpixel((x, y))[3] >= 128 else 0
          for y in range(32) for x in range(32)]

image = Image.new("P", (32, 32))
image.putpalette([channel for color in icon_palette for channel in color] + [0] * (768 - 48))
image.putdata(pixels)
image.save(assets / "icon.png", transparency=0)

bitmap = bytes((pixels[y * 32 + x] << 4) | pixels[y * 32 + x + 1]
               for y in range(31, -1, -1) for x in range(0, 32, 2))
offset = 14 + 40 + 16 * 4
header = struct.pack("<2sIHHI", b"BM", offset + len(bitmap), 0, 0, offset)
header += struct.pack("<IiiHHIIiiII", 40, 32, 32, 1, 4, 0, len(bitmap), 0, 0, 16, 16)
colors = bytes(channel for r, g, b in icon_palette for channel in (b, g, r, 0))
(assets / "icon.bmp").write_bytes(header + colors + bitmap)

gui_palette = [
    (0, 0, 0), (8, 9, 13), (18, 20, 28), (35, 39, 53),
    (135, 80, 255), (191, 159, 255), (155, 158, 174), (232, 234, 242),
    (36, 33, 69), (51, 56, 73), (13, 15, 21), (240, 126, 135),
    (164, 131, 255), (107, 0, 250), (85, 89, 112), (255, 255, 255),
]

def rgb15(color):
    r, g, b = color
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)




gui_colors = [0] + [min(range(1, 15), key=lambda index: sum(
    (gui_palette[index][channel] - color[channel]) ** 2 for channel in range(3)))
    for color in icon_palette[1:]]
source = "// Generated by tools/build_assets.py from the supplied DSiDrop logo.\n#pragma once\n"
source += "static const unsigned short rfPalette[16] = {" + ",".join(hex(rgb15(c)) for c in gui_palette) + "};\n"
source += "static const unsigned short rfIconPalette[16] = {" + ",".join(hex(rgb15(c)) for c in icon_palette) + "};\n"
source += "static const unsigned char rfIconGuiColors[16] = {" + ",".join(map(str, gui_colors)) + "};\n"
source += "static const unsigned char rfIcon[1024] = {\n"
source += "\n".join("    " + ",".join(map(str, pixels[y * 32:y * 32 + 32])) + "," for y in range(32))
source += "\n};\n"
(root / "include" / "icon.h").write_text(source, encoding="ascii")
print("Imported supplied DSiDrop pictogram: assets/icon.bmp, assets/icon.png, include/icon.h")

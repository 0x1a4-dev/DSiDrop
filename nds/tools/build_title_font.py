"""Bake proportional, antialiased native fonts; no font file is shipped.

Usage: python nds/tools/build_title_font.py [REGULAR.ttf] [--bold-font BOLD.ttf]
Defaults to Segoe UI on Windows and DejaVu Sans on Linux. Pass both font files
to reproduce the same typeface on another build machine. Generated headers are
checked in, so building the handheld app does not require installed fonts.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("regular_font", nargs="?", type=Path)
parser.add_argument("--bold-font", type=Path)
args = parser.parse_args()


def select_font(explicit, candidates):
    if explicit:
        if not explicit.is_file():
            parser.error(f"Font file does not exist: {explicit}")
        return str(explicit)
    for candidate in candidates:
        if Path(candidate).is_file():
            return candidate
    parser.error("No supported system font found. Pass REGULAR.ttf and --bold-font BOLD.ttf.")


regular_path = select_font(args.regular_font, (
    "C:/Windows/Fonts/segoeui.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
    "/System/Library/Fonts/Supplemental/Arial.ttf",
))
bold_path = select_font(args.bold_font, (
    str(Path(regular_path).with_name("segoeuib.ttf")),
    str(Path(regular_path).with_name("DejaVuSans-Bold.ttf")),
    str(Path(regular_path).with_name("LiberationSans-Bold.ttf")),
    str(Path(regular_path).with_name("Arial Bold.ttf")),
    regular_path,
))


def raster_font(characters, size, cell, baseline, path):
    # FreeType's native-size grayscale rasterizer keeps small stems aligned to
    # DS pixels; all four coverage levels are retained by the canvas renderer.
    font = ImageFont.truetype(path, size)
    widths, glyphs = [], []
    for character in characters:
        image = Image.new("L", (cell, cell))
        ImageDraw.Draw(image).text((0, baseline), character, font=font, fill=255, anchor="ls")
        levels = [(value * 3 + 127) // 255 for value in image.get_flattened_data()]
        glyphs.append([sum(levels[index + offset] << (offset * 2) for offset in range(4))
                       for index in range(0, cell * cell, 4)])
        # A single pixel of breathing room remains between native glyphs.
        widths.append(min(cell, max(2, round(font.getlength(character)) + 1)))
    return widths, glyphs


def arrays(name, widths, glyphs):
    source = f"static const unsigned char {name}Widths[{len(widths)}] = {{" + ",".join(map(str, widths)) + "};\n"
    source += f"static const unsigned char {name}Glyphs[{len(glyphs)}][{len(glyphs[0])}] = {{\n"
    source += "\n".join("    {" + ",".join(map(str, glyph)) + "}," for glyph in glyphs) + "\n};\n"
    return source


ascii_characters = "".join(chr(code) for code in range(32, 127))
header = "// Generated by tools/build_title_font.py; native proportional glyphs, 2-bit coverage.\n#pragma once\n"
body = raster_font(ascii_characters, 12, 16, 12, regular_path)
(root / "include/title_font.h").write_text(header + arrays("title", *body), encoding="ascii")

brand_chars = "DSirop"
brand = raster_font(brand_chars, 26, 32, 26, bold_path)
(root / "include/brand_font.h").write_text(
    header + f'static const char brandChars[] = "{brand_chars}";\n' + arrays("brand", *brand), encoding="ascii")

source = header
for name, size, cell, baseline, path in (
    ("caption", 11, 16, 12, regular_path),
    ("heading", 16, 24, 18, bold_path),
    ("metric", 26, 32, 26, regular_path),
):
    source += arrays(name, *raster_font("0123456789%" if name == "metric" else ascii_characters,
                                     size, cell, baseline, path))
(root / "include/ui_font.h").write_text(source, encoding="ascii")
print(f"Built native 12px body / 11px caption / 16px heading fonts: {ImageFont.truetype(regular_path, 12).getname()[0]}")

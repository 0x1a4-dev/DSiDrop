"""Rasterize a small title font for the native 4bpp canvas (no font file is shipped)."""
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(sys.argv[1] if len(sys.argv) > 1 else "C:/Windows/Fonts/segoeuib.ttf", 12)
widths, glyphs = [], []
for code in range(32, 127):
    character = chr(code)
    width = min(16, max(2, round(font.getlength(character)) + 1))
    image = Image.new("L", (16, 16))
    ImageDraw.Draw(image).text((0, 12), character, font=font, fill=255, anchor="ls")

    levels = [(value * 3 + 127) // 255 for value in image.get_flattened_data()]
    glyphs.append(bytes(sum(levels[i + offset] << (offset * 2) for offset in range(4)) for i in range(0, 256, 4)))
    widths.append(width)
source = "// Generated by tools/build_title_font.py; 12px raster glyphs, 2-bit coverage.\n#pragma once\n"
source += "static const unsigned char titleWidths[95] = {" + ",".join(map(str, widths)) + "};\n"
source += "static const unsigned char titleGlyphs[95][64] = {\n"
source += "\n".join("    {" + ",".join(map(str, glyph)) + "}," for glyph in glyphs) + "\n};\n"
(root / "include/title_font.h").write_text(source, encoding="ascii")
print("Built 12px proportional title glyphs: include/title_font.h")
brand_font = ImageFont.truetype(sys.argv[1] if len(sys.argv) > 1 else "C:/Windows/Fonts/segoeuib.ttf", 26)
brand_chars = "DSirop"
brand_widths, brand_glyphs = [], []
for character in brand_chars:
    image = Image.new("L", (32, 32))
    ImageDraw.Draw(image).text((0, 26), character, font=brand_font, fill=255, anchor="ls")
    levels = [(value * 3 + 127) // 255 for value in image.get_flattened_data()]
    brand_glyphs.append(bytes(sum(levels[i + offset] << (offset * 2) for offset in range(4)) for i in range(0, 1024, 4)))
    brand_widths.append(round(brand_font.getlength(character)) + 1)
source = '// Generated by tools/build_title_font.py; native 26px DSiDrop title.\n#pragma once\n'
source += f'static const char brandChars[] = "{brand_chars}";\n'
source += "static const unsigned char brandWidths[] = {" + ",".join(map(str, brand_widths)) + "};\n"
source += "static const unsigned char brandGlyphs[][256] = {\n"
source += "\n".join("    {" + ",".join(map(str, glyph)) + "}," for glyph in brand_glyphs) + "\n};\n"
(root / "include/brand_font.h").write_text(source, encoding="ascii")
print("Built 26px DSiDrop title: include/brand_font.h")

import assert from "node:assert/strict";
import path from "node:path";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { registerTypescript } from "./test-support/typescript.mjs";
const { require } = registerTypescript();
const { DeviceLibrary, deviceGames, parseDeviceInventory, managedRomPath, sdLibraryPath } = require(path.resolve("src/lib/server/device-library.ts"));
const { themeCrc } = require(path.resolve("src/lib/server/theme-package.ts"));
const { gameSaveTargets, matchingDeviceGame, supportsAutomaticRestore } = require(path.resolve("src/lib/device-library.ts"));
assert.equal(supportsAutomaticRestore("1.15.0"), false);
assert.equal(supportsAutomaticRestore("1.16.0"), true);
assert.equal(supportsAutomaticRestore(""), false);
const romPath = "/roms/nds/Pokemon [aaaaaaaa].nds", savePath = "/roms/nds/saves/Pokemon [aaaaaaaa].sav";
const row = (target, size = 1024) => `${Buffer.from(target).toString("hex")}\t${size}\t123\t1234abcd`;
const files = parseDeviceInventory(`RFINVENTORY1\n${row(romPath)}\n${row(savePath)}\n`);
const datasets = [{ meta: { id: "nds", coverBase: "https://example.test/" }, roms: [{ m: "a".repeat(32), n: "Pokemon", t: "Pokemon", r: "World", c: "Pokemon" }] }];
const games = deviceGames(files, [savePath], datasets);
assert.equal(games.length, 1); assert.equal(games[0].title, "Pokemon");
assert.equal(games[0].cover, "https://example.test/Pokemon.png"); assert.deepEqual(games[0].savePaths, [savePath]);
assert.equal(matchingDeviceGame(games[0], { ...games[0], path: "/games/Pokemon.nds" }), true);
assert.equal(matchingDeviceGame(games[0], { ...games[0], romId: "b".repeat(32) }), false);
assert.equal(matchingDeviceGame(games[0], { ...games[0], installed: false }), false);
assert.ok(gameSaveTargets({ ...games[0], path: "/games/Pokemon.nds", savePaths: [] }).includes("/games/saves/Pokemon.sav"));
const archived = deviceGames([], [savePath], datasets);
assert.equal(archived[0].installed, false); assert.equal(archived[0].cover, "https://example.test/Pokemon.png");
for (const target of ["/../a.nds", "/roms//a.nds", "fat:/a.nds"]) assert.throws(() => sdLibraryPath(target));
for (const target of ["/_nds/TWiLightMenu/main.nds", "/BOOT.NDS", "/DSiDrop.nds", "/roms/a.sav"]) assert.equal(managedRomPath(target), false);
assert.throws(() => parseDeviceInventory(`RFINVENTORY1\n${row(romPath)}\n${row(romPath)}\n`));
assert.equal(deviceGames([{ ...files[0], path: "/games/Unknown.nds" }], [], datasets)[0].cover, null);
console.log("PASS: device inventory, game/save matching, archived covers and protected paths");
const directory = await mkdtemp(path.join(tmpdir(), "dsidrop-library-"));
try {
	const mac = "001122334455", manifest = path.join(directory, "inventory.json");
	const library = new DeviceLibrary(manifest, async () => datasets, async () => [savePath, "/games/Unknown.sav", "/another/Unknown.sav"]);
	const fingerprint = "1234567890abcdef";
	const params = new URLSearchParams({ mac, session: "abcdef", cap: "1", fingerprint });
	assert.throws(() => library.poll(new URLSearchParams({ mac, session: "abcdef" })));
	const command = (await library.poll(params)).trim().split("\t");
	assert.equal(command[1], "scan");
	const bytes = Buffer.from(`RFINVENTORY1\n${row(romPath)}\n${row(savePath)}\n`);
	await library.upload(new Request(`http://localhost/api/devices/library/sync?mac=${mac}&job=${command[2]}&fingerprint=${fingerprint}&crc=${themeCrc(bytes).toString(16).padStart(8, "0")}`, { method: "PUT", headers: { "Content-Length": String(bytes.length) }, body: bytes }));
	params.set("finished", command[2]); params.set("ok", "1");
	assert.equal(await library.poll(params), "RFLIBRARY1\tnone\n");
	const snapshot = await library.snapshot(mac), installed = snapshot.games.find((game) => game.installed);
	assert.ok(snapshot.scannedAt); assert.equal(installed.cover, "https://example.test/Pokemon.png");
	assert.equal(snapshot.storage, null);
	params.set("total", String(64 * 1024 ** 3)); params.set("free", String(32 * 1024 ** 3));
	await library.poll(params);
	const storage = (await library.snapshot(mac)).storage;
	assert.equal(storage.total, 64 * 1024 ** 3); assert.equal(storage.free, 32 * 1024 ** 3); assert.ok(storage.updatedAt);
	assert.throws(() => library.poll(new URLSearchParams({ mac, session: "abcdef", cap: "1", total: "10", free: "11" })));
	assert.throws(() => library.poll(new URLSearchParams({ mac, session: "abcdef", cap: "1", total: "0", free: "0" })));
	params.set("free", "0"); await library.poll(params);
	assert.equal((await library.snapshot(mac)).storage.free, 0);
	assert.equal((await library.snapshot("aabbccddeeff")).storage, null);
	await assert.rejects(() => library.change({ mac, action: "delete", game: installed.id }));
	await assert.rejects(() => library.change({ mac, action: "delete", game: "unknown", confirmed: true }));
	await library.change({ mac, action: "delete", game: installed.id, confirmed: true });
	const deletion = (await library.poll(params)).trim().split("\t");
	assert.equal(deletion[1], "delete"); assert.equal(Buffer.from(deletion[3], "hex").toString(), romPath);
	assert.equal(deletion[4], "1024"); assert.equal(deletion[6], "1234abcd");
	params.set("finished", deletion[2]);
	await library.poll(params);
	const removed = await library.snapshot(mac);
	assert.equal(removed.games.some((game) => game.installed), false);
	assert.equal(removed.games.find((game) => game.cover)?.savePaths[0], savePath);
	const reopened = new DeviceLibrary(manifest, async () => datasets, async () => [savePath]);
	assert.equal((await reopened.snapshot(mac)).games[0].cover, "https://example.test/Pokemon.png");
	assert.equal((await reopened.snapshot(mac)).storage.total, 64 * 1024 ** 3);
	const noRestartScan = new DeviceLibrary(manifest, async () => datasets, async () => [savePath]);
	assert.equal(await noRestartScan.poll(new URLSearchParams({ mac, session: "abcdef", cap: "1", startup: "0", fingerprint })), "RFLIBRARY1\tnone\n", "Server restart during an active app does not trigger a scan");
	const refresh = (await reopened.poll(new URLSearchParams({ mac, session: "abcd01", cap: "1", startup: "1", fingerprint }))).trim().split("\t");
	assert.equal(refresh[1], "scan");
	await reopened.upload(new Request(`http://localhost/api/devices/library/sync?mac=${mac}&job=${refresh[2]}&fingerprint=${fingerprint}&crc=${themeCrc(bytes).toString(16).padStart(8, "0")}`, { method: "PUT", headers: { "Content-Length": String(bytes.length) }, body: bytes }));
	await reopened.poll(new URLSearchParams({ mac, session: "abcd01", cap: "1", startup: "0", fingerprint, finished: refresh[2], ok: "1" }));
	assert.equal(await reopened.poll(new URLSearchParams({ mac, session: "bcdefa", cap: "1", fingerprint })), "RFLIBRARY1\tnone\n", "Unchanged startup after server restart skips scanning");
	assert.equal(await reopened.poll(new URLSearchParams({ mac, session: "cdefab", cap: "1", fingerprint })), "RFLIBRARY1\tnone\n", "Another unchanged app startup skips scanning");
	await reopened.change({ mac, action: "scan" });
	const manual = (await reopened.poll(new URLSearchParams({ mac, session: "cdefab", cap: "1", fingerprint }))).trim().split("\t");
	assert.equal(manual[1], "scan", "Manual check bypasses an unchanged fingerprint");
	await reopened.poll(new URLSearchParams({ mac, session: "cdefab", cap: "1", fingerprint, finished: manual[2], ok: "1" }));
	const changed = (await reopened.poll(new URLSearchParams({ mac, session: "defabc", cap: "1", fingerprint: "abcdef1234567890" }))).trim().split("\t");
	assert.equal(changed[1], "scan", "Changed startup requests a scan");
	assert.equal((await reopened.poll(new URLSearchParams({ mac, session: "defabc", cap: "1", fingerprint: "abcdef1234567890", finished: changed[2], ok: "0" }))).trim(), "RFLIBRARY1\tnone");
	assert.equal((await reopened.poll(new URLSearchParams({ mac, session: "efabcd", cap: "1", fingerprint: "abcdef1234567890" }))).trim().split("\t")[1], "scan", "Failed scans do not save the new fingerprint");
	assert.throws(() => reopened.poll(new URLSearchParams({ mac, session: "abcdef", cap: "1", fingerprint: "invalid" })));
	console.log("PASS: unchanged startups skip scanning, manual checks override it and failed scans retry next startup");
	console.log("PASS: per-device SD capacity, zero free space, persistence and invalid storage values");
	console.log("PASS: scan/upload, version gate, browser-confirmed deletion, persistence and preserved save backups");
} finally { await rm(directory, { recursive: true, force: true }); }